"""Plot ITL-load metrics vs in/out length for each concurrency level.

Input can be a sweep ``results.jsonl`` generated by:
``baseline_itl_load_sweep.py`` or ``itl_load_sweep.py``.

For each ``conc`` value this script saves one figure with 4 subplots:
  - tok/s
  - mITL (ms)
  - p99_req_ms (ms)
  - TTFT_ms (ms)

X-axis is in/out length label (e.g. ``512/512``).
"""

from __future__ import annotations

import argparse
import json
import statistics
from collections import defaultdict
from pathlib import Path
from typing import Any

try:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
except ImportError as exc:
    raise SystemExit(
        "matplotlib is required. Install it in your venv: pip install matplotlib"
    ) from exc


def _to_float(v: Any) -> float | None:
    if v is None:
        return None
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def _aggregate(values: list[float], mode: str) -> float | None:
    if not values:
        return None
    if mode == "median":
        return float(statistics.median(values))
    if mode == "mean":
        return float(statistics.fmean(values))
    # "first"
    return float(values[0])


def load_rows(jsonl_path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for line in jsonl_path.read_text().splitlines():
        line = line.strip()
        if not line:
            continue
        rows.append(json.loads(line))
    return rows


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--jsonl",
        type=Path,
        default=Path("/data/ben/kv_phase_a_internal/baseline_itl_load_v1/results.jsonl"),
        help="Path to results.jsonl",
    )
    p.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="Output directory for PNGs (default: <jsonl-dir>/graphs_by_concurrency)",
    )
    p.add_argument(
        "--aggregate",
        choices=["median", "mean", "first"],
        default="median",
        help="How to aggregate repeated trials per (conc, in/out)",
    )
    p.add_argument(
        "--title-prefix",
        default="Baseline vLLM",
        help="Prefix used in figure titles",
    )
    p.add_argument(
        "--combined-png",
        default="all_concurrency_metrics.png",
        help="Filename for single combined PNG (set empty to skip)",
    )
    ns = p.parse_args()

    if not ns.jsonl.is_file():
        raise SystemExit(f"missing input: {ns.jsonl}")

    out_dir = ns.output_dir or (ns.jsonl.parent / "graphs_by_concurrency")
    out_dir.mkdir(parents=True, exist_ok=True)

    rows = load_rows(ns.jsonl)
    if not rows:
        raise SystemExit(f"no rows in {ns.jsonl}")

    # grouped[(conc, in_len, out_len)][metric] = [values...]
    grouped: dict[tuple[int, int, int], dict[str, list[float]]] = defaultdict(
        lambda: defaultdict(list)
    )
    io_pairs: set[tuple[int, int]] = set()
    concs: set[int] = set()

    for r in rows:
        conc = r.get("concurrency")
        in_len = r.get("input_len")
        out_len = r.get("output_len")
        if conc is None or in_len is None or out_len is None:
            continue
        try:
            conc_i = int(conc)
            in_i = int(in_len)
            out_i = int(out_len)
        except (TypeError, ValueError):
            continue

        key = (conc_i, in_i, out_i)
        concs.add(conc_i)
        io_pairs.add((in_i, out_i))

        tps = _to_float(r.get("throughput_tok_per_s"))
        mitl = _to_float(r.get("concurrent_mean_itl_s"))
        p99 = _to_float(r.get("concurrent_mean_p99_itl_s"))
        ttft = _to_float(r.get("concurrent_ttft_s_mean"))

        if tps is not None:
            grouped[key]["tok_s"].append(tps)
        if mitl is not None:
            grouped[key]["mITL_ms"].append(mitl * 1000.0)
        if p99 is not None:
            grouped[key]["p99_req_ms"].append(p99 * 1000.0)
        if ttft is not None:
            grouped[key]["TTFT_ms"].append(ttft * 1000.0)

    io_sorted = sorted(io_pairs, key=lambda x: (x[0], x[1]))
    conc_sorted = sorted(concs)
    x_labels = [f"{i}/{o}" for i, o in io_sorted]
    x_idx = list(range(len(io_sorted)))

    metric_defs: list[tuple[str, str]] = [
        ("tok_s", "tok/s"),
        ("mITL_ms", "mITL (ms)"),
        ("p99_req_ms", "p99_req_ms"),
        ("TTFT_ms", "TTFT_ms"),
    ]

    # Save a compact CSV of plotted values for traceability.
    csv_path = out_dir / "aggregated_values.csv"
    csv_lines = ["concurrency,input_len,output_len,tok_s,mITL_ms,p99_req_ms,TTFT_ms,n_trials"]

    # Cache aggregated series for optional combined figure.
    series_by_conc: dict[int, dict[str, list[float]]] = {}

    for conc in conc_sorted:
        fig, axes = plt.subplots(2, 2, figsize=(14, 9), sharex=True)
        ax_list = [axes[0][0], axes[0][1], axes[1][0], axes[1][1]]
        fig.suptitle(f"{ns.title_prefix} — conc={conc}", fontsize=14)

        n_trials_ref = 0
        for metric_key, _metric_label in metric_defs:
            for in_len, out_len in io_sorted:
                vals = grouped[(conc, in_len, out_len)][metric_key]
                if vals:
                    n_trials_ref = max(n_trials_ref, len(vals))

        per_metric: dict[str, list[float]] = {}
        for ax, (metric_key, metric_ylabel) in zip(ax_list, metric_defs):
            y: list[float | None] = []
            for in_len, out_len in io_sorted:
                vals = grouped[(conc, in_len, out_len)][metric_key]
                y.append(_aggregate(vals, ns.aggregate))
            y_plot = [float("nan") if v is None else float(v) for v in y]
            per_metric[metric_key] = y_plot

            ax.plot(x_idx, y_plot, marker="o", linewidth=2)
            ax.set_ylabel(metric_ylabel)
            ax.grid(True, alpha=0.3)
            ax.set_xticks(x_idx)
            ax.set_xticklabels(x_labels, rotation=25, ha="right")
        series_by_conc[conc] = per_metric

        for i, (in_len, out_len) in enumerate(io_sorted):
            vals_tok = grouped[(conc, in_len, out_len)]["tok_s"]
            vals_mitl = grouped[(conc, in_len, out_len)]["mITL_ms"]
            vals_p99 = grouped[(conc, in_len, out_len)]["p99_req_ms"]
            vals_ttft = grouped[(conc, in_len, out_len)]["TTFT_ms"]
            csv_lines.append(
                ",".join(
                    [
                        str(conc),
                        str(in_len),
                        str(out_len),
                        f"{_aggregate(vals_tok, ns.aggregate) or ''}",
                        f"{_aggregate(vals_mitl, ns.aggregate) or ''}",
                        f"{_aggregate(vals_p99, ns.aggregate) or ''}",
                        f"{_aggregate(vals_ttft, ns.aggregate) or ''}",
                        str(max(len(vals_tok), len(vals_mitl), len(vals_p99), len(vals_ttft), 0)),
                    ]
                )
            )

        fig.text(
            0.5,
            0.01,
            f"x-axis = input/output length, aggregation = {ns.aggregate}, trials ~= {n_trials_ref}",
            ha="center",
            fontsize=9,
        )
        plt.tight_layout(rect=(0, 0.03, 1, 0.96))
        out_png = out_dir / f"conc_{conc}_metrics.png"
        fig.savefig(out_png, dpi=180)
        plt.close(fig)
        print(f"wrote {out_png}")

    if ns.combined_png:
        nrows = len(conc_sorted)
        ncols = len(metric_defs)
        fig, axes = plt.subplots(
            nrows, ncols, figsize=(4.2 * ncols, 2.9 * nrows), sharex=True
        )
        if nrows == 1:
            axes = [axes]  # type: ignore[assignment]
        fig.suptitle(
            f"{ns.title_prefix} — all conc levels (aggregation={ns.aggregate})",
            fontsize=14,
        )
        for r, conc in enumerate(conc_sorted):
            row_axes = axes[r]
            for c, (metric_key, metric_ylabel) in enumerate(metric_defs):
                ax = row_axes[c]
                y_plot = series_by_conc[conc][metric_key]
                ax.plot(x_idx, y_plot, marker="o", linewidth=1.8)
                ax.grid(True, alpha=0.3)
                if r == 0:
                    ax.set_title(metric_ylabel, fontsize=10)
                if c == 0:
                    ax.set_ylabel(f"conc={conc}", fontsize=10)
                ax.set_xticks(x_idx)
                ax.set_xticklabels(x_labels, rotation=25, ha="right", fontsize=8)
        plt.tight_layout(rect=(0, 0.03, 1, 0.95))
        combined_path = out_dir / ns.combined_png
        fig.savefig(combined_path, dpi=190)
        plt.close(fig)
        print(f"wrote {combined_path}")

    csv_path.write_text("\n".join(csv_lines) + "\n")
    print(f"wrote {csv_path}")


if __name__ == "__main__":
    main()

